"""Curated, role-specific preparation roadmaps.

Each topic carries:
  concepts  – "Name — one-line explanation" strings (what to learn)
  notes     – last-minute revision bullets
  qa        – (interview question, model answer) pairs
  pitfalls  – common mistakes
  docs      – (title, url) official docs / high-quality free resources
  videos    – YouTube search phrases (turned into search links so they never go stale)
"""
from typing import Any, Dict, List
from urllib.parse import quote_plus


def T(title: str, description: str, hours: int, difficulty: str, concepts: List[str], notes: List[str],
      qa: List[tuple], docs: List[tuple], videos: List[str], pitfalls: List[str] = None) -> Dict[str, Any]:
    return {"title": title, "description": description, "estimated_hours": hours, "difficulty": difficulty,
            "concepts": concepts, "notes": notes, "qa": qa, "docs": docs, "videos": videos, "pitfalls": pitfalls or []}


def S(title: str, description: str, topics: List[Dict[str, Any]]) -> Dict[str, Any]:
    return {"title": title, "description": description, "topics": topics}


def youtube_link(query: str) -> str:
    return f"https://www.youtube.com/results?search_query={quote_plus(query)}"


